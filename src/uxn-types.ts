// ============================================================================
// Файл: uxn-types.ts
// Общие типы и контракты виртуальной машины Uxn
// Единый источник типов разрывает циклическую зависимость
// между uxn-vm.ts и opcodes/*
// ============================================================================

// ----------------------------------------------------------------------------
// УСТРОЙСТВА
// ----------------------------------------------------------------------------

/**
 * Интерфейс для внешних устройств (экран, клавиатура, аудио и т.д.)
 */
export interface Device {
    /**
     * Выполняет операцию DEI (чтение из устройства)
     */
    dei(vm: VMState, target: number): void;

    /**
     * Выполняет операцию DEO (запись в устройство)
     * @returns true если ВМ должна продолжать работу, false для выхода
     */
    deo(vm: VMState, target: number): boolean;
}

// ----------------------------------------------------------------------------
// СТЕКИ И ФЛАГИ
// ----------------------------------------------------------------------------

/**
 * Флаги опкодов
 */
export interface OpcodeFlags {
    short: boolean;       // 0x80 - работать с 16-битными значениями
    returnStack: boolean; // 0x40 - использовать стек возвратов
    keep: boolean;        // 0x20 - не удалять значения из стека
}

/**
 * Стек виртуальной машины
 */
export interface Stack {
    data: Uint8Array;  // 256 байт
    index: number;     // 0-255
}

// ----------------------------------------------------------------------------
// СОСТОЯНИЕ ВИРТУАЛЬНОЙ МАШИНЫ
// ----------------------------------------------------------------------------

/**
 * Структурный контракт состояния ВМ, которым пользуются опкоды и устройства.
 * Класс Uxn реализует этот интерфейс, поэтому uxn-opcodes.ts больше не
 * импортирует класс Uxn напрямую.
 */
export interface VMState {
    stack: Stack;        // Стек данных
    ret: Stack;          // Стек возвратов
    ram: Uint8Array;     // 65536 байт RAM
    dev: Uint8Array;     // 256 байт памяти устройств
    device: Device;      // Текущее устройство
}

/**
 * Сигнатура функции-опкода.
 * @returns новый PC, либо null если выполнение должно остановиться (BRK)
 */
export type OpcodeFn = (vm: VMState, flags: OpcodeFlags, pc: number) => number | null;
